"""Generate the integer hardware gain ROM and the matching review tables."""
from pathlib import Path
import json
import math

ROOT = Path(__file__).resolve().parents[1]


def make_tables():
    tables = []
    for amount in (1.1, 1.8, 2.4):
        gains, targets = [], []
        for value in range(256):
            toe = min(1.0, value / 12.0)
            toe = toe * toe * (3.0 - 2.0 * toe)
            desired = value * (1 + amount * (1 - value / 255.0) ** 2 * toe)
            target = min(255, int(math.floor(desired + .5)))
            if value:
                lower = max(256, (target * 256 - 128 + value - 1) // value)
                upper = ((target + 1) * 256 - 129) // value
                gain = min(upper, max(lower, int(desired * 256 / value + .5)))
            else:
                gain = 256
            assert 256 <= gain <= 1023
            assert (value * gain + 128) >> 8 == target
            gains.append(gain)
            targets.append(target)
        assert all(a <= b for a, b in zip(targets, targets[1:]))
        assert targets[0] == 0 and targets[-1] == 255
        tables.append(dict(gain_q8=gains, target=targets))
    return tables


if __name__ == '__main__':
    tables = make_tables()
    rows = ['// Generated by tools/generate_lowlight_lut.py. Packed strong/medium/weak Q8 gains.',
            'module hdmi_lowlight_gain_rom(input wire clk, input wire [7:0] address, output reg [29:0] gains);',
            'always @(posedge clk) begin', '    case (address)']
    for value in range(256):
        packed = sum(table['gain_q8'][value] << (10 * index) for index, table in enumerate(tables))
        rows.append("        8'd%d: gains <= 30'h%08x;" % (value, packed))
    rows += ["        default: gains <= 30'h10040100;", '    endcase', 'end', 'endmodule', '']
    (ROOT/'src/hdmi_lowlight_gain_rom.v').write_text('\n'.join(rows), encoding='ascii')
    (ROOT/'tools/lowlight_lut.json').write_text(json.dumps(tables, indent=2), encoding='ascii')
    print('LOWLIGHT_LUT_PASS: three monotonic 256-entry curves; black/white endpoints; bounded common RGB gain')
